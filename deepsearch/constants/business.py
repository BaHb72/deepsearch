class Status(Enum):
    """
    订单状态枚举。
    
    定义了订单在其生命周期中可能处于的所有状态。
    """
    SUBMITTING = "提交中"  # 订单正在提交
    NOTTRADED = "未成交"  # 订单已提交但未成交
    PARTTRADED = "部分成交"  # 订单部分成交
